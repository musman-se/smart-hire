def test_a_long_legacy_skill_name_does_not_stop_the_upgrade(alembic_config: Config) -> None:
    """Cutting a name to 64 characters can leave a trailing space, which the
    ck_skills_name_normalised check refuses. b4f2d8e61a37 trims after it cuts."""
    command.upgrade(alembic_config, "7c1e5b2a9d40")
    long_name = "a" * 63 + " tail of a very long legacy skill"
    _query(
        f"""
        INSERT INTO candidates (id, email, full_name, skills)
        VALUES ('00000000-0000-0000-0000-000000000007', 'long@example.com', 'Long Name',
                ARRAY['{long_name}'])
        """
    )

    command.upgrade(alembic_config, "b4f2d8e61a37")

    assert _query("SELECT name FROM skills") == [("a" * 63,)]


def test_existing_candidates_get_an_account_that_cannot_sign_in(alembic_config: Config) -> None:
    """d5e8a2f41c07 moves the email to users and makes candidates.id a foreign key to
    users.id. Each existing candidate must come out with an account sharing its id — the
    foreign key cannot be added otherwise — and with no password: nobody would know an
    invented one."""
    command.upgrade(alembic_config, "b7e3d05a9c12")
    _query(
        """
        INSERT INTO candidates (id, email, full_name)
        VALUES ('00000000-0000-0000-0000-000000000008', 'before.auth@example.com', 'Pre Auth')
        """
    )

    command.upgrade(alembic_config, "d5e8a2f41c07")

    assert _query("SELECT id::text, email, password_hash, role::text FROM users") == [
        ("00000000-0000-0000-0000-000000000008", "before.auth@example.com", None, "CANDIDATE")
    ]

    command.downgrade(alembic_config, "b7e3d05a9c12")

    assert _query("SELECT email FROM candidates") == [("before.auth@example.com",)]


def _insert_job(job_id: int, title: str, description: str) -> None:
    _query(
        f"""
        INSERT INTO jobs (id, title, description, employment_type, status)
        VALUES ('00000000-0000-0000-0000-{job_id:012d}', '{title}', '{description}',
                'FULL_TIME', 'DRAFT')
        """
    )


def test_migrated_text_bounds_match_the_models(alembic_config: Config) -> None:
    """`alembic check` does not compare CHECK constraints, so a changed constant with no
    migration would pass it — and the API and the database would quietly disagree. This
    probes the migrated schema at each edge of the bounds the models declare."""
    command.upgrade(alembic_config, "head")

    _insert_job(9, "x" * TITLE_MIN_LENGTH, "x" * DESCRIPTION_MIN_LENGTH)
    _insert_job(10, "x" * TITLE_MAX_LENGTH, "x" * DESCRIPTION_MAX_LENGTH)

    for title, description in [
        ("x" * (TITLE_MIN_LENGTH - 1), "x" * DESCRIPTION_MIN_LENGTH),
        ("x" * TITLE_MIN_LENGTH, "x" * (DESCRIPTION_MIN_LENGTH - 1)),
        ("x" * TITLE_MIN_LENGTH, "x" * (DESCRIPTION_MAX_LENGTH + 1)),
    ]:
        with pytest.raises(Exception, match="ck_jobs_(title|description)_length"):
            _insert_job(11, title, description)

    assert _query("SELECT count(*) FROM jobs") == [(2,)]


def test_a_job_outside_the_text_bounds_stops_the_upgrade(alembic_config: Config) -> None:
    """81276ef5beaf names the jobs to fix rather than altering a recruiter's text."""
    command.upgrade(alembic_config, "d5e8a2f41c07")
    _insert_job(12, "QA", "A job whose title predates the minimum.")

    with pytest.raises(RuntimeError, match="00000000-0000-0000-0000-000000000012"):
        command.upgrade(alembic_config, "81276ef5beaf")

    _query("UPDATE jobs SET title = 'QA Engineer'")
    command.upgrade(alembic_config, "81276ef5beaf")
    command.downgrade(alembic_config, "d5e8a2f41c07")
    _insert_job(13, "QA", "Allowed again once the checks are gone.")


def test_existing_recruiters_get_a_profile_named_from_their_email(
    alembic_config: Config,
) -> None:
    """45e197ff436b adds recruiters, and the code expects every recruiter account to have
    a profile. Accounts from before get one, named from the email's local part since
    full_name is required; candidates get none."""
    command.upgrade(alembic_config, "81276ef5beaf")
    _query(
        """
        INSERT INTO users (id, email, role) VALUES
            ('00000000-0000-0000-0000-000000000014', 'alice.ahmed@example.com', 'RECRUITER'),
            ('00000000-0000-0000-0000-000000000015', '_@example.com', 'RECRUITER'),
            ('00000000-0000-0000-0000-000000000016', 'cand@example.com', 'CANDIDATE')
        """
    )

    command.upgrade(alembic_config, "45e197ff436b")

    assert _query("SELECT id::text, full_name, title FROM recruiters ORDER BY id") == [
        ("00000000-0000-0000-0000-000000000014", "Alice Ahmed", None),
        ("00000000-0000-0000-0000-000000000015", "Recruiter", None),
    ]

    command.downgrade(alembic_config, "81276ef5beaf")

    assert _query("SELECT count(*) FROM users") == [(3,)]


def test_downgrading_the_admin_role_turns_admins_back_into_recruiters(
    alembic_config: Config,
) -> None:
    """6b2d9e4f1a83 adds ADMIN to user_role. Postgres cannot drop an enum value, so the
    downgrade rebuilds the type — and must first move admins to a value that survives."""
    command.upgrade(alembic_config, "6b2d9e4f1a83")
    _query(
        """
        INSERT INTO users (id, email, role, deactivated_at) VALUES
            ('00000000-0000-0000-0000-000000000017', 'owner@example.com', 'ADMIN', NULL),
            ('00000000-0000-0000-0000-000000000018', 'left@example.com', 'RECRUITER', now())
        """
    )

    command.downgrade(alembic_config, "45e197ff436b")

    assert _query("SELECT email, role::text FROM users ORDER BY email") == [
        ("left@example.com", "RECRUITER"),
        ("owner@example.com", "RECRUITER"),
    ]
    assert _query("SELECT enum_range(NULL::user_role)::text") == [("{RECRUITER,CANDIDATE}",)]

    command.upgrade(alembic_config, "6b2d9e4f1a83")
    assert _query("SELECT enum_range(NULL::user_role)::text") == [("{RECRUITER,CANDIDATE,ADMIN}",)]
