"""Migrations — replayed from scratch against a throwaway database.

The rest of the suite builds its schema with metadata.create_all(), which proves the
*models* but says nothing about the *migrations*. Those are a separate artefact, and they
can be wrong in ways the models never show:

- a downgrade that leaves objects behind, so the next upgrade fails;
- a revision whose result depends on today's models rather than on history;
- a data migration that loses rows;
- a model change nobody wrote a migration for.

Each of those happened, or nearly happened, while this file was being written. Each
test below would have caught one.

These tests are synchronous on purpose. Alembic's env.py drives its async engine with
asyncio.run(), which refuses to start inside an already-running event loop.
"""

import asyncio
from collections.abc import Iterator
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import text
from sqlalchemy.ext.asyncio import create_async_engine

from app.core.config import settings
from app.jobs.models import (
    DESCRIPTION_MAX_LENGTH,
    DESCRIPTION_MIN_LENGTH,
    TITLE_MAX_LENGTH,
    TITLE_MIN_LENGTH,
)

BACKEND_DIR = Path(__file__).resolve().parent.parent
DB_NAME = f"{settings.test_database_name}_migrations"


def _url(database: str) -> str:
    base, _, _ = settings.database_url.rpartition("/")
    return f"{base}/{database}"


def _admin(sql: str) -> None:
    async def run() -> None:
        engine = create_async_engine(_url("postgres"), isolation_level="AUTOCOMMIT")
        try:
            async with engine.connect() as conn:
                await conn.execute(text(sql))
        finally:
            await engine.dispose()

    asyncio.run(run())


def _query(sql: str) -> list[tuple]:
    async def run() -> list[tuple]:
        engine = create_async_engine(_url(DB_NAME))
        try:
            async with engine.begin() as conn:
                result = await conn.execute(text(sql))
                return [tuple(row) for row in result] if result.returns_rows else []
        finally:
            await engine.dispose()

    return asyncio.run(run())


@pytest.fixture
def alembic_config() -> Iterator[Config]:
    """A fresh, empty database, and an Alembic config pointed at it."""
    try:
        _admin(f'DROP DATABASE IF EXISTS "{DB_NAME}" WITH (FORCE)')
        _admin(f'CREATE DATABASE "{DB_NAME}"')
    except Exception as exc:  # noqa: BLE001 - any connection failure means "no database"
        pytest.skip(f"PostgreSQL unreachable ({type(exc).__name__}). Run: docker compose up -d db")

    config = Config(str(BACKEND_DIR / "alembic.ini"))
    config.attributes["database_url"] = _url(DB_NAME)
    config.attributes["configure_logger"] = False
    yield config

    _admin(f'DROP DATABASE IF EXISTS "{DB_NAME}" WITH (FORCE)')


def _user_objects() -> list[tuple]:
    """Every table and enum type in the public schema, except Alembic's own table."""
    return _query(
        """
        SELECT 'table', tablename FROM pg_tables
        WHERE schemaname = 'public' AND tablename <> 'alembic_version'
        UNION ALL
        SELECT 'type', typname FROM pg_type
        WHERE typtype = 'e' AND typnamespace = 'public'::regnamespace
        """
    )


def test_upgrade_from_empty_matches_the_models(alembic_config: Config) -> None:
    """`alembic check` after a full upgrade: the migrations build exactly the schema the
    models describe. Fails if a model changed without a migration."""
    command.upgrade(alembic_config, "head")

    command.check(alembic_config)  # raises AutogenerateDiffsDetected on any drift


def test_downgrade_to_base_removes_everything(alembic_config: Config) -> None:
    """A downgrade must leave nothing behind, or the next upgrade collides with it.
    This is the test that caught the initial revision leaving its enum types in place."""
    command.upgrade(alembic_config, "head")
    command.downgrade(alembic_config, "base")

    assert _user_objects() == []

    # And the proof that matters: history can be replayed on top.
    command.upgrade(alembic_config, "head")
    command.check(alembic_config)


def test_skills_data_migration_preserves_every_skill(alembic_config: Config) -> None:
    """b4f2d8e61a37 moves array elements into join tables, then drops the arrays.
    Autogenerate writes only the schema half; this proves the hand-written data half."""
    command.upgrade(alembic_config, "7c1e5b2a9d40")  # the last revision with arrays
    _query(
        """
        INSERT INTO jobs (id, title, description, employment_type, status, required_skills)
        VALUES ('00000000-0000-0000-0000-000000000001', 'Old Role', 'A legacy job row.',
                'FULL_TIME', 'DRAFT', '{python,kafka,python}')
        """
    )
    _query(
        """
        INSERT INTO candidates (id, email, full_name, skills)
        VALUES ('00000000-0000-0000-0000-000000000002', 'old@example.com', 'Old Person',
                '{python,go}')
        """
    )

    command.upgrade(alembic_config, "b4f2d8e61a37")

    assert _query("SELECT name FROM skills ORDER BY name") == [("go",), ("kafka",), ("python",)]
    assert _query(
        "SELECT s.name FROM job_skills js JOIN skills s ON s.id = js.skill_id ORDER BY 1"
    ) == [("kafka",), ("python",)]  # the repeated "python" became one link
    assert _query(
        "SELECT s.name FROM candidate_skills cs JOIN skills s ON s.id = cs.skill_id ORDER BY 1"
    ) == [("go",), ("python",)]

    command.downgrade(alembic_config, "7c1e5b2a9d40")

    assert _query("SELECT required_skills FROM jobs") == [(["kafka", "python"],)]
    assert _query("SELECT skills FROM candidates") == [(["go", "python"],)]


def test_removing_job_statuses_moves_jobs_back_to_draft(alembic_config: Config) -> None:
    """Postgres cannot drop an enum value, so a3d9e7c15b20's downgrade rebuilds the type.
    A job sitting in a removed state must come out as DRAFT, not block the downgrade."""
    command.upgrade(alembic_config, "a3d9e7c15b20")
    _query(
        """
        INSERT INTO jobs (id, title, description, employment_type, status)
        VALUES ('00000000-0000-0000-0000-000000000003', 'Mid-publish', 'Being processed.',
                'FULL_TIME', 'PROCESSING')
        """
    )

    command.downgrade(alembic_config, "e91a6c3f0b58")

    assert _query("SELECT status::text FROM jobs") == [("DRAFT",)]
    assert _query(
        "SELECT enumlabel FROM pg_enum JOIN pg_type t ON t.oid = enumtypid "
        "WHERE t.typname = 'job_status' ORDER BY enumsortorder"
    ) == [("DRAFT",), ("PUBLISHED",), ("CLOSED",)]


